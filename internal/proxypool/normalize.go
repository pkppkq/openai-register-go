// Package proxypool ports app.py's manual proxy-pool layer: the input
// normalizer (app.py:2396 normalize_proxy_url), the pool-text parser
// (app.py:2421 parse_proxy_pool_text), the four rotating pools the Tk app kept
// inside Text widgets (app.py:17316 _rotate_proxy_pool_values) and the
// 代理模式=全走本地代理 gate (app.py:16712 _local_proxy_only_enabled) that forces
// every pool read and every reuse-proxy read to come back empty.
//
// proxyhealth has its own unexported normalizeProxyURL; it is a deliberately
// minimal scheme-fixer for already-stored URLs. This one is the full UI-input
// parser and is not interchangeable with it.
package proxypool

