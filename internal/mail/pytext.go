var pyFoldMap = buildPyFoldMap()

func buildPyFoldMap() map[rune]string {
	out := make(map[rune]string, 132)
	for _, record := range strings.Split(pyFoldPairs, " ") {
		if record == "" {
			continue
		}
		key, size := utf8.DecodeRuneInString(record)
		out[key] = record[size:]
	}
	return out
}

// pyFoldCherokee is the Cherokee half of the casefold table, which folds to
// UPPERCASE rather than lowercase: the syllabary's lowercase letters were added
// to Unicode long after the uppercase ones, so CaseFolding.txt keeps the old
// (uppercase) form as the fold target. Go's strings.ToLower goes the other way.
func pyFoldCherokee(r rune) (rune, bool) {
	switch {
	case r >= 0x13A0 && r <= 0x13F5:
		return r, true
	case r >= 0xAB70 && r <= 0xABBF:
		return r - 0xAB70 + 0x13A0, true
	}
	return 0, false
}

// pyCaseFold is str.casefold(): FULL Unicode case folding, which the Go
// standard library does not provide. ß folds to "ss" and ſ to "s", so casefold
// is NOT strings.ToLower — every deactivation / security marker in this file is
// compared against a folded haystack, and "found as compromiſed" is a match in
// Python.
func pyCaseFold(s string) string {
	if isASCII(s) {
		return strings.ToLower(s)
	}
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		if v, ok := pyFoldMap[r]; ok {
			b.WriteString(v)
			continue
		}
		if v, ok := pyFoldCherokee(r); ok {
			b.WriteRune(v)
			continue
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}

// pyDigitValue is Python's int(ch) for one character: the decimal value of a
// Unicode digit, or (0, false) outside category Nd.
//
// Nd is laid out as complete, aligned runs of ten, so the offset from the start
// of the containing range modulo ten IS the value. Several ranges hold more
// than one run (U+1D7CE..U+1D7FF is five), which is why walking backwards to
// the nearest non-Nd rune would answer 9 for U+1D7D8 MATHEMATICAL DOUBLE-STRUCK
// DIGIT ZERO.
func pyDigitValue(r rune) (int, bool) {
	if r <= unicode.MaxLatin1 {
		if r >= '0' && r <= '9' {
			return int(r - '0'), true
		}
		return 0, false
	}
	for _, rg := range unicode.Nd.R16 {
		if rune(rg.Lo) <= r && r <= rune(rg.Hi) && rg.Stride == 1 {
			return int((r - rune(rg.Lo)) % 10), true
		}
	}
	for _, rg := range unicode.Nd.R32 {
		if rune(rg.Lo) <= r && r <= rune(rg.Hi) && rg.Stride == 1 {
			return int((r - rune(rg.Lo)) % 10), true
		}
	}
	return 0, false
}

// pyDatetimeTimestamp is datetime.timestamp(), which returns a FLOAT carrying
// microseconds — CPython computes ((delta_days*86400 + delta_seconds)*10**6 +
// microseconds) / 10**6, so UnixMicro()/1e6 is the same double.
// time.Time.Unix() truncates to whole seconds, which backdated a Cloud Mail
// message by up to a second and could push it under the caller's min_timestamp.
func pyDatetimeTimestamp(t time.Time) float64 {
	return float64(t.UnixMicro()) / 1e6
}

// pyFloat is Python's float(s) restricted to the shape its one caller has
// already fullmatched: `\d+(?:\.\d+)?` over Python's `\d`, i.e. Nd digits.
// CPython's float() accepts a fullwidth or Arabic-Indic spelling and
// strconv.ParseFloat does not, so the digits are folded to ASCII first.
func pyFloat(s string) float64 {
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		if v, ok := pyDigitValue(r); ok {
			b.WriteByte(byte('0' + v))
			continue
		}
		b.WriteRune(r)
	}
	// A ParseFloat range error still yields ±Inf, which is what float() returns
	// for an overlong digit run, so the error is deliberately dropped.
	f, _ := strconv.ParseFloat(b.String(), 64)
	return f
}

func isASCII(s string) bool {
	for i := 0; i < len(s); i++ {
		if s[i] >= utf8.RuneSelf {
			return false
		}
	}
	return true
}

