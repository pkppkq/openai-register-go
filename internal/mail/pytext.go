// pySplitResult is urllib.parse.SplitResult. Path/Query are RAW — urlsplit
// never percent-decodes, while url.URL.Path is already decoded.
type pySplitResult struct {
	Scheme   string
	Netloc   string
	Path     string
	Query    string
	Fragment string
}

var pySchemeCharRe = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9+.\-]*$`)

// pyC0AndSpace is WHATWG "C0 control or space" — U+0000..U+0020.
const pyC0AndSpace = "\x00\x01\x02\x03\x04\x05\x06\a\b\t\n\v\f\r\x0e\x0f" +
	"\x10\x11\x12\x13\x14\x15\x16\x17\x18\x19\x1a\x1b\x1c\x1d\x1e\x1f "

var pyURLUnsafeStripper = strings.NewReplacer("\t", "", "\n", "", "\r", "")

// pyURLSplit mirrors urllib.parse.urlsplit(), which never fails.
func pyURLSplit(value string) pySplitResult {
	// CPython: lstrip C0-control-or-space, then delete every tab/CR/LF.
	rest := pyURLUnsafeStripper.Replace(strings.TrimLeft(value, pyC0AndSpace))
	var out pySplitResult
	if i := strings.IndexByte(rest, ':'); i > 0 && pySchemeCharRe.MatchString(rest[:i]) {
		out.Scheme = pyLower(rest[:i])
		rest = rest[i+1:]
	}
	if strings.HasPrefix(rest, "//") {
		body := rest[2:]
		end := len(body)
		for _, c := range []byte{'/', '?', '#'} {
			if j := strings.IndexByte(body, c); j >= 0 && j < end {
				end = j
			}
		}
		out.Netloc, rest = body[:end], body[end:]
	}
	if i := strings.IndexByte(rest, '#'); i >= 0 {
		rest, out.Fragment = rest[:i], rest[i+1:]
	}
	if i := strings.IndexByte(rest, '?'); i >= 0 {
		rest, out.Query = rest[:i], rest[i+1:]
	}
	out.Path = rest
	return out
}

// Hostname mirrors SplitResult.hostname: netloc minus userinfo and port,
// lowercased ("" where Python returns None).
func (s pySplitResult) Hostname() string {
	host := s.Netloc
	if i := strings.LastIndexByte(host, '@'); i >= 0 {
		host = host[i+1:]
	}
	if strings.Contains(host, "[") && strings.Contains(host, "]") {
		host = host[strings.Index(host, "[")+1:]
		if j := strings.Index(host, "]"); j >= 0 {
			host = host[:j]
		}
	} else if i := strings.IndexByte(host, ':'); i >= 0 {
		host = host[:i]
	}
	return pyLower(host)
}

// pyUnquote is urllib.parse.unquote(s) with its defaults (encoding="utf-8",
// errors="replace"): every well-formed %XX is decoded, a malformed one is kept
// verbatim, '+' is left ALONE (that is unquote_plus, which url.QueryUnescape
// does), and undecodable bytes become U+FFFD.
func pyUnquote(value string) string {
	if !strings.Contains(value, "%") {
		return value
	}
	out := make([]byte, 0, len(value))
	for i := 0; i < len(value); i++ {
		if value[i] == '%' && i+2 < len(value) {
			hi, okHi := pyUnhex(value[i+1])
			lo, okLo := pyUnhex(value[i+2])
			if okHi && okLo {
				out = append(out, hi<<4|lo)
				i += 2
				continue
			}
		}
		out = append(out, value[i])
	}
	return strings.ToValidUTF8(string(out), "�")
}

func pyUnhex(c byte) (byte, bool) {
	switch {
	case c >= '0' && c <= '9':
		return c - '0', true
	case c >= 'a' && c <= 'f':
		return c - 'a' + 10, true
	case c >= 'A' && c <= 'F':
		return c - 'A' + 10, true
	}
	return 0, false
}

// pyReIgnoreCaseLetters are the non-ASCII code points that CPython's
// re.IGNORECASE folds into the ASCII letters: U+0130 İ and U+0131 ı (which Go's
// `(?i)`, driven by unicode.SimpleFold orbits, does NOT reach) plus U+017F ſ
// and U+212A KELVIN SIGN (which it does — listed so the class is the complete
// CPython answer rather than "the two Go misses").
//
// Only reEmailMatch is widened with them: it is the one `(?i)` pattern here
// whose input is an operator- or sender-supplied address. The cue words
// ("openai", "deactivated", ...) come from OpenAI's own mail and never arrive
// spelled with a Turkish dotted I.
const pyReIgnoreCaseLetters = `\x{0130}\x{0131}\x{017F}\x{212A}`
