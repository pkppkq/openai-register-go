package mail

// pytext.go holds the `re` and `str` equivalences this package needs to
// reproduce CPython on MAIL text. Same idea (and the same three character
// classes) as internal/worker/pytext.go; duplicated on purpose so the mail port
// stays a leaf that does not import the worker.
//
// Mail bodies are the worst possible input for Go's ASCII-only defaults:
// html_to_text unescapes `&nbsp;` LAST (app.py:6283), so every rendered HTML
// mail hands the classifiers U+00A0 where Python's `\s` sees whitespace and
// RE2's does not. The three equivalences below were established by comparing
// CPython against Go over U+0000..U+10FFFF:
//
//	Python str-mode `\s`  ==  Go [\s\x{000B}\x{001C}-\x{001F}\x{0085}\p{Z}]
//	Python str-mode `\w`  ==  Go [\p{L}\p{N}_]
//	Python str-mode `\d`  ==  Go \p{Nd}
//
// Concrete defects this file removes, each reproduced against app.py:
//   - "account&nbsp;has&nbsp;been&nbsp;deactivated": Python collapses the NBSPs
//     and matches the ban marker; ASCII `\s+` left them and the ban was missed.
//   - an OTP written in fullwidth or Arabic-Indic digits: Python's `\d{6}`
//     matches, `[0-9]{6}` does not, and the code came back "".
//   - a Chinese subject "中文deactivated": Python's `\b` sees NO boundary between
//     文 and d (both are `\w`), RE2's ASCII `\b` does, so Go flagged a ban that
//     Python did not.

