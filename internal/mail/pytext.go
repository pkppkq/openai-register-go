// pyTruthy is Python's bool(v) for the shapes json.Unmarshal produces: None,
// False, 0, "", [] and {} are falsy, everything else is truthy.
func pyTruthy(v interface{}) bool {
	switch t := v.(type) {
	case nil:
		return false
	case bool:
		return t
	case string:
		return t != ""
	case float64:
		return t != 0
	case []interface{}:
		return len(t) != 0
	case map[string]interface{}:
		return len(t) != 0
	}
	return true
}

// pyOr is Python's `a or b or c`: the first truthy operand, else the last one.
// Truthiness is tested on the RAW value, before any str()/strip().
func pyOr(values ...interface{}) interface{} {
	for i, v := range values {
		if pyTruthy(v) || i == len(values)-1 {
			return v
		}
	}
	return nil
}

// pyStr is Python's str(v) over json.loads output. A JWT `aud` claim is
// routinely an ARRAY, and Python renders that as "['https://…']" — brackets,
// quotes and ", " separators — which is what lands in the operator-facing log
// line. fmt's "%v" would print "[https://…]".
func pyStr(v interface{}) string {
	switch t := v.(type) {
	case nil:
		return "None"
	case string:
		return t
	case bool:
		if t {
			return "True"
		}
		return "False"
	case float64:
		// CPython's json.loads yields an int for an integral JSON number, so
		// str() prints no ".0" and never an exponent.
		if t == math.Trunc(t) && math.Abs(t) < 1e16 {
			return strconv.FormatInt(int64(t), 10)
		}
		return strconv.FormatFloat(t, 'g', -1, 64)
	case []interface{}:
		parts := make([]string, 0, len(t))
		for _, item := range t {
			parts = append(parts, pyRepr(item))
		}
		return "[" + strings.Join(parts, ", ") + "]"
	case map[string]interface{}:
		// Go maps have no order; CPython dicts do. Unreachable for `aud`/`scp`
		// (never objects in a Microsoft token) and only ever a log string.
		keys := make([]string, 0, len(t))
		for k := range t {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		parts := make([]string, 0, len(keys))
		for _, k := range keys {
			parts = append(parts, pyRepr(k)+": "+pyRepr(t[k]))
		}
		return "{" + strings.Join(parts, ", ") + "}"
	}
	return fmt.Sprintf("%v", v)
}

// pyRepr is Python's repr(v) — the form str() uses for items INSIDE a
// container. Only strings differ from str(): they gain quotes.
func pyRepr(v interface{}) string {
	s, ok := v.(string)
	if !ok {
		return pyStr(v)
	}
	quote := "'"
	if strings.Contains(s, "'") && !strings.Contains(s, `"`) {
		quote = `"`
	}
	var b strings.Builder
	b.WriteString(quote)
	for _, r := range s {
		switch {
		case r == '\\':
			b.WriteString(`\\`)
		case string(r) == quote:
			b.WriteString(`\` + quote)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteString(quote)
	return b.String()
}

