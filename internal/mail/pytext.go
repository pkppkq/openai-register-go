// pyWSClass is the BODY of a character class equal to Python's str-mode `\s`.
const pyWSClass = `\s\x{000B}\x{001C}-\x{001F}\x{0085}\p{Z}`

// pyWS is one Python-`\s` character, ready to embed in a pattern.
const pyWS = `[` + pyWSClass + `]`

// pyDigit is the BODY of a character class equal to Python's str-mode `\d`
// (category Nd, 680 code points); pyNonDigit is Python's `[^\d]`.
const (
	pyDigit    = `\p{Nd}`
	pyNonDigit = `[^` + pyDigit + `]`
)

// pyWordChar is the BODY of a character class equal to Python's str-mode `\w`;
// pyNonWord is one non-`\w` character.
const (
	pyWordChar = `\p{L}\p{N}_`
	pyNonWord  = `[^` + pyWordChar + `]`
)

// pyB wraps a pattern in Python-compatible (Unicode-aware) word boundaries,
// standing in for `\b(...)\b`.
//
// RE2 has no lookaround, so the boundary characters are CONSUMED. Every call
// site below is either a boolean MatchString or takes only the FIRST match, and
// consuming one leading delimiter shifts every candidate start position by the
// same single character, so the leftmost match — and therefore the captured
// group — is unchanged. Do NOT reuse this for FindAll: two adjacent matches
// that share a delimiter would collapse into one.
func pyB(inner string) string {
	return `(?:^|` + pyNonWord + `)(?:` + inner + `)(?:$|` + pyNonWord + `)`
}

// pyIsSpace is str.isspace() for one character. unicode.IsSpace covers 25 of
// the 29 code points and omits the four information separators U+001C..U+001F,
// which str.strip() does remove.
func pyIsSpace(r rune) bool {
	return unicode.IsSpace(r) || (r >= 0x1c && r <= 0x1f)
}

// pyStrip is str.strip(); pyRStrip is str.rstrip().
func pyStrip(s string) string  { return strings.TrimFunc(s, pyIsSpace) }
func pyRStrip(s string) string { return strings.TrimRightFunc(s, pyIsSpace) }

// pyLower is str.lower(). Full lowercase mapping differs from Go's simple
// mapping at exactly ONE code point, U+0130 LATIN CAPITAL LETTER I WITH DOT
// ABOVE, which lowercases to two runes (i + U+0307); verified by walking
// U+0000..U+10FFFF.
//
// DIVERGENCE: CPython also applies the Greek final-sigma context rule, so
// "ΟΔΟΣ".lower() is "οδος" while this returns "οδοσ". Reproducing it needs the
// Cased/Case_Ignorable properties Go does not export, and no call site here
// lowercases Greek prose — the inputs are URLs and ASCII marker words.
func pyLower(s string) string {
	if strings.ContainsRune(s, 'İ') {
		s = strings.ReplaceAll(s, "İ", "i̇")
	}
	return strings.ToLower(s)
}

