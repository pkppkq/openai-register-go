// cherokeeFold is the one script that case-folds UPWARDS: CaseFolding.txt maps
// the lowercase syllables U+AB70..U+ABBF and U+13F8..U+13FD onto the historic
// uppercase ones, and leaves U+13A0..U+13F5 alone. unicode.ToLower does the
// opposite in every one of those 172 code points, which is why they cannot go
// through the ToLower fast path. Kept as ranges rather than 172 table rows.
func cherokeeFold(r rune) (rune, bool) {
	switch {
	case r >= 0x13A0 && r <= 0x13F5:
		return r, true // already the folded form
	case r >= 0x13F8 && r <= 0x13FD:
		return r - 8, true
	case r >= 0xAB70 && r <= 0xABBF:
		return r - 0x97D0, true
	}
	return 0, false
}

func needsFullFold(r rune) bool {
	if r < 0xB5 { // ASCII and the C1 block never differ
		return false
	}
	if _, ok := pyFoldExtra[r]; ok {
		return true
	}
	_, ok := cherokeeFold(r)
	return ok
}

// caseFold mirrors str.casefold() (app.py:19101/19103/19106/19116/19130/19143).
// The common case (ASCII address, CJK status) never touches the table.
func caseFold(s string) string {
	if !strings.ContainsFunc(s, needsFullFold) {
		return strings.ToLower(s)
	}
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		if mapped, ok := pyFoldExtra[r]; ok {
			b.WriteString(mapped)
			continue
		}
		if folded, ok := cherokeeFold(r); ok {
			b.WriteRune(folded)
			continue
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}

// pyLower mirrors str.lower() (app.py:19025/19082/19750). U+0130 is the only
// code point whose full lowercase mapping is longer than one rune, and
// strings.ToLower collapses it to a bare "i" — which would merge the row
// identities of "İ@x.com" and "i@x.com" (Key is what a selection set holds).
//
// DIVERGENCE: str.lower() also applies the context-sensitive Final_Sigma rule
// ("ΟΔΟΣ".lower() == "οδος", ours gives "οδοσ"). Reproducing it needs the Cased
// and Case_Ignorable derived properties, which Go does not export. Nothing
// compares one of these strings against a Python-produced one — Key, the group
// picker and the plan-type test all fold both sides in Go — so no outcome
// differs; see TestPyLowerFinalSigmaDivergence. The same call is spelled the
// same way in internal/opll and internal/logs.
func pyLower(s string) string {
	if strings.ContainsRune(s, 'İ') {
		s = strings.ReplaceAll(s, "İ", "i̇")
	}
	return strings.ToLower(s)
}

// ndDigitValue returns the decimal value of an Nd rune, i.e. Python's
// int(chr(cp)) for a single decimal digit.
//
// Unicode requires every Nd character to belong to a set of ten consecutive
// codepoints starting at that script's zero, so the value is the offset from
// the start of the run — but adjacent runs are NOT separated by a gap. The
// five Mathematical digit blocks U+1D7CE..U+1D7FF are one unbroken span of 50
// digits, and a naive "walk down at most nine places until the previous rune
// is not a digit" answers 9 for all 40 codepoints after the first block
// (int("𝟢") is 0, not 9 — that bug made HasK12Success reject a 2xx written in
// mathematical digits). Walk to the start of the WHOLE contiguous span, which
// is always a zero and always a multiple of ten long, then take the offset
// modulo ten.
func ndDigitValue(r rune) (int, bool) {
	if !unicode.IsDigit(r) {
		return 0, false
	}
	if r <= '9' {
		return int(r - '0'), true
	}
	start := r
	for start > 0 && unicode.IsDigit(start-1) {
		start--
	}
	return int(r-start) % 10, true
}

// pyDigitInt mirrors `s.isdigit() and int(s)` (app.py:19073-19075): every rune
// must be a decimal digit, then the string converts as a non-negative int.
//
// Two deliberate narrowings of Python:
//   - Python's str.isdigit() is also true for Numeric_Type=Digit characters
//     outside Nd (superscripts such as "²"), and int() then raises ValueError
//     on them — a live crash path. Go's unicode.IsDigit is Nd-only, so this
//     returns ok=false there instead of panicking. (Verified against CPython:
//     the code points int() accepts as a lone digit are EXACTLY Nd.)
//   - Python ints are arbitrary precision, Go's are 64-bit, so an absurdly long
//     digit string SATURATES at math.MaxInt instead of wrapping. It used to stop
//     accumulating past 1e9, which silently answered 1234567890 for
//     int("12345678901234") — wrong for AttemptCount, which does display the
//     number. Saturation cannot change HasK12Success: anything that overflows is
//     far above 300.
func pyDigitInt(s string) (int, bool) {
	if s == "" {
		return 0, false
	}
	value := 0
	saturated := false
	for _, r := range s {
		d, ok := ndDigitValue(r)
		if !ok {
			return 0, false
		}
		if saturated {
			continue
		}
		if value > (math.MaxInt-d)/10 {
			value, saturated = math.MaxInt, true
			continue
		}
		value = value*10 + d
	}
	return value, true
}

// pyIntStrip is the padding int() itself tolerates, which is NOT str.strip()'s
// set: verified against CPython over all 1,112,064 code points, int() accepts
// every str.isspace() character EXCEPT the C0 information separators
// U+001C..U+001F. That set is exactly Go's unicode.IsSpace, i.e. TrimSpace —
// pyStrip would be wrong here, and would make Go answer 8 for "\x1c8\x1f" where
// CPython raises ValueError (which pyInt reports as 0, see below).
func pyIntStrip(s string) string { return strings.TrimSpace(s) }

// pyIntDigits mirrors the digit grammar of int(str): decimal digits with single
// underscores BETWEEN digits ("1_0" is 10, "_1", "1_" and "1__0" all raise).
// Python allows the separator with non-ASCII digits too — int("٩_٩") is 99.
func pyIntDigits(s string) (int, bool) {
	if s == "" {
		return 0, false
	}
	cleaned := s
	if strings.ContainsRune(s, '_') {
		var b strings.Builder
		b.Grow(len(s))
		prevDigit := false
		runes := []rune(s)
		for i, r := range runes {
			if r == '_' {
				if !prevDigit || i+1 >= len(runes) || !unicode.IsDigit(runes[i+1]) {
					return 0, false
				}
				prevDigit = false
				continue
			}
			b.WriteRune(r)
			prevDigit = unicode.IsDigit(r)
		}
		cleaned = b.String()
	}
	return pyDigitInt(cleaned)
}

// pyInt mirrors int(v) for JSON-decoded values (app.py:19093's
// `max(0, int(... or 0))`). Python truncates floats toward zero and accepts a
// surrounding-whitespace-padded decimal string. Where Python would raise
// (TypeError/ValueError on a dict, list or non-numeric string) this returns 0:
// app.py has no handler there, so raising would only crash the render pass.
func pyInt(v any) int {
	switch t := v.(type) {
	case nil:
		return 0
	case bool:
		if t {
			return 1
		}
		return 0
	case int:
		return t
	case int64:
		return int(t)
	case float64:
		if math.IsNaN(t) || math.IsInf(t, 0) {
			return 0
		}
		return int(math.Trunc(t))
	case json.Number:
		if n, err := t.Int64(); err == nil {
			return int(n)
		}
		if f, err := t.Float64(); err == nil {
			return int(math.Trunc(f))
		}
		return 0
	case string:
		s := pyIntStrip(t)
		neg := false
		if strings.HasPrefix(s, "+") || strings.HasPrefix(s, "-") {
			neg = s[0] == '-'
			s = s[1:]
		}
		n, ok := pyIntDigits(s)
		if !ok {
			return 0
		}
		if neg {
			return -n
		}
		return n
	}
	return 0
}
