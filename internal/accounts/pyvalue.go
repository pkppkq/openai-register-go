// Ports of the Python value semantics (truthiness, str(), str.strip(), int(),
// str.isdigit(), str.casefold(), re.split(r"\s+", ...)) that app.py's derived
// -status logic leans on. The lookup maps hold raw encoding/json values (any),
// the same shape Python sees after json.load, so every conversion below must
// follow Python rules, not Go ones.
package accounts

import (
	"encoding/json"
	"math"
	"regexp"
	"strconv"
	"strings"
	"unicode"
)

// pyFalsy reports whether Python would treat v as falsy in an `or` chain.
// Note this is NOT strings.TrimSpace(...)==""; Python's `or` does not strip —
// " " is truthy while "" is falsy (app.py:19058/19062/19063 rely on this).
func pyFalsy(v any) bool {
	switch t := v.(type) {
	case nil:
		return true
	case string:
		return t == ""
	case bool:
		return !t
	case float64:
		return t == 0
	case int:
		return t == 0
	case int64:
		return t == 0
	case json.Number:
		f, err := t.Float64()
		return err == nil && f == 0
	case map[string]any:
		return len(t) == 0
	case []any:
		return len(t) == 0
	}
	return false
}

// pyStr mirrors str(v) for JSON-decoded values. json.Unmarshal yields float64
// for every JSON number while Python's json keeps int and float distinct; the
// Python side only ever stores these fields as int or str (app.py:14034/14038,
// 18665), so integral floats are formatted without ".0" to match str(int).
// For dict/list only truthiness-after-strip of the result matters at our call
// sites, so a stable non-empty stand-in replaces Python's repr.
func pyStr(v any) string {
	switch t := v.(type) {
	case nil:
		return "None"
	case string:
		return t
	case bool:
		if t {
			return "True"
		}
		return "False"
	case json.Number:
		return t.String()
	case float64:
		if t == math.Trunc(t) && math.Abs(t) < 1e15 {
			return strconv.FormatInt(int64(t), 10)
		}
		return strconv.FormatFloat(t, 'g', -1, 64)
	case int:
		return strconv.Itoa(t)
	case int64:
		return strconv.FormatInt(t, 10)
	case map[string]any:
		return "{...}"
	case []any:
		return "[...]"
	}
	return "?"
}

// pyStrOr mirrors the ubiquitous str(v or "") idiom (app.py:19058 etc.).
func pyStrOr(v any) string {
	if pyFalsy(v) {
		return ""
	}
	return pyStr(v)
}

// orChain mirrors `a or b or ...`: the first truthy operand, nil when none is.
func orChain(vals ...any) any {
	for _, v := range vals {
		if !pyFalsy(v) {
			return v
		}
	}
	return nil
}

// pyIsSpace mirrors Python's str.isspace() for one rune: Go's unicode.IsSpace
// plus the C0 information separators U+001C..U+001F, which Python counts as
// whitespace and Go does not. Both agree on NBSP U+00A0, NEL U+0085 and Z*.
func pyIsSpace(r rune) bool {
	return unicode.IsSpace(r) || (r >= 0x1c && r <= 0x1f)
}

// pyStrip mirrors str.strip(). (Known port trap: rendered text carries NBSP,
// and Python strips it here — strings.TrimSpace happens to agree on NBSP but
// not on U+001C-1F.)
func pyStrip(s string) string {
	return strings.TrimFunc(s, pyIsSpace)
}

// reWhitespace is the Go equivalent of Python's `\s+` for str patterns
// (app.py:19116). Python's `\s` matches exactly str.isspace(); Go's RE2 `\s`
// is the ASCII class [\t\n\f\r ] and omits even \v, so \v, U+001C..U+001F,
// U+0085 and all of \p{Z} (NBSP, ideographic space U+3000, ...) are added back
// explicitly. Rendered Chinese UI text routinely carries U+00A0 and U+3000.
var reWhitespace = regexp.MustCompile(`[\s\x{000B}\x{001C}-\x{001F}\x{0085}\p{Z}]+`)

